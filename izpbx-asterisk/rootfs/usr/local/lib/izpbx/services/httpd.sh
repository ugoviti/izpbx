# shellcheck shell=bash
# Apache 2.4 (Debian layout) configured from the environment, same output as
# cfgService_httpd of 20.16 with the Debian paths (design C1, C2):
#   20.16 /etc/httpd/conf.d/virtual.conf  -> /etc/apache2/sites-available/izpbx.conf
#   20.16 httpd.conf ServerName           -> /etc/apache2/conf-available/izpbx.conf
#   20.16 httpd.conf Listen               -> /etc/apache2/ports.conf
#   20.16 httpd.conf User/Group           -> APACHE_RUN_USER/GROUP in /etc/apache2/envvars
# The sites, confs and modules (rewrite, ssl) are enabled at build
# (build/runtime.sh). The vhost text is the 20.16 one, apart from what has no
# Debian equivalent: log paths under ${APACHE_LOG_DIR}, the passphrase helper
# and SSL session cache of Debian, and the cipher list of Debian's ssl.conf
# instead of the system crypto policy of the Rocky Linux based 20.16 (PROFILE=SYSTEM).
# shellcheck source=../env.sh
. /usr/local/lib/izpbx/env.sh

: "${HTTPD_CONF_DIR:=/etc/apache2}"
HTTPD_VHOST="$HTTPD_CONF_DIR/sites-available/izpbx.conf"
HTTPD_GLOBAL="$HTTPD_CONF_DIR/conf-available/izpbx.conf"
HTTPD_CIPHERS="HIGH:!aNULL"
: "${CERTKEYLOC:=/etc/asterisk/keys}"

_httpd_allow_from() {
  local ip
  if [ -n "$HTTPD_ALLOW_FROM" ]; then
    # shellcheck disable=SC2086 # a space separated list, quotes removed as in 20.16
    for ip in ${HTTPD_ALLOW_FROM//\'/}; do echo "    Require ip ${ip}"; done
  else
    echo "    Require all granted"
  fi
}

_httpd_redirect_default() {
  cat <<'R'
  <IfModule mod_rewrite.c>
    RewriteEngine on
    RewriteCond %{REQUEST_URI} !\.well-known/acme-challenge
    RewriteCond %{REQUEST_URI} !\.freepbx-known
    RewriteCond %{HTTPS} off
    #RewriteCond %{HTTP_HOST} ^www\.(.*)$ [NC]
    RewriteRule .? https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
  </IfModule>
R
}

_httpd_redirect_fqdn() {
  cat <<'R'
# enable http to https automatic rewrite
<IfModule mod_rewrite.c>
  RewriteEngine on
  RewriteCond %{REQUEST_URI} !\.well-known/acme-challenge
  RewriteCond %{REQUEST_URI} !\.freepbx-known
  RewriteCond %{HTTPS} off
  #RewriteCond %{HTTP_HOST} ^www\.(.*)$ [NC]
  RewriteRule .? https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
</IfModule>

R
}

# self-signed certificate (10 years) when the files are missing, or when the
# CN is the default "izpbx" and APP_FQDN is set (as 20.16)
_httpd_selfsigned() {
  local cn="" subj="/CN=izpbx"
  [ -n "$APP_FQDN" ] && subj="/CN=$APP_FQDN"
  [ -e "$HTTPD_HTTPS_CERT_FILE" ] && cn=$(openssl x509 -noout -subject -in "$HTTPD_HTTPS_CERT_FILE" | sed 's/.*CN = //;s/, .*//')
  if [ ! -e "$HTTPD_HTTPS_CERT_FILE" ] || [ ! -e "$HTTPD_HTTPS_KEY_FILE" ]; then
    log_warn "httpd: missing certificate files ($HTTPD_HTTPS_CERT_FILE, $HTTPD_HTTPS_KEY_FILE): generating a self-signed certificate"
  elif [ -n "$APP_FQDN" ] && [ "$cn" == "izpbx" ]; then
    log_warn "httpd: certificate CN '$cn' does not match APP_FQDN '$APP_FQDN': generating a new self-signed certificate"
  else
    [ -n "$APP_FQDN" ] && [ "$APP_FQDN" != "$cn" ] &&
      log_warn "httpd: certificate CN '$cn' ($HTTPD_HTTPS_CERT_FILE) does not match APP_FQDN '$APP_FQDN': replace the certificate"
    return 0
  fi
  mkdir -p "$(dirname "$HTTPD_HTTPS_CERT_FILE")" "$(dirname "$HTTPD_HTTPS_KEY_FILE")"
  openssl req -subj "$subj" -new -newkey rsa:2048 -sha256 -days 3650 -nodes -x509 \
    -keyout "$HTTPD_HTTPS_KEY_FILE" -out "$HTTPD_HTTPS_CERT_FILE" 2>/dev/null
}

# the Debian default page in the webroot (P3-27): a volume seeded before the
# build removed it, or by a .dist that still had it, would show "Apache2 Debian
# Default Page" instead of FreePBX (index.html comes first in DirectoryIndex).
# Removed only when it is exactly the page of the package: an index.html of
# the user stays.
httpd_remove_default_page() {
  local page=/var/www/html/index.html ref=/usr/share/apache2/default-site/index.html
  [ -f "$page" ] && [ -f "$ref" ] && cmp -s "$page" "$ref" || return 0
  rm -f "$page"
  log_info "httpd: Debian default page removed from the webroot (FreePBX index.php serves /)"
}

cfg_httpd() {
  httpd_remove_default_page
  log_info "httpd: ServerName ${SERVERNAME}, port ${APP_PORT_HTTP}$([ "$HTTPD_HTTPS_ENABLED" == "true" ] && echo ", https ${APP_PORT_HTTPS}")"
  # LimitRequestBody (vhost file) is not applied by mod_proxy_fcgi to the PHP
  # requests (20.16 had mod_php): bodies over 128M (PHP post_max_size) are
  # refused by Content-Length before reaching php-fpm, with the same 413
  printf '# generated by izpbx-init (services/httpd.sh)\nServerName %s\n\n<If "%%{HTTP:Content-Length} -gt 134217728">\n  Redirect 413 /\n</If>\n' "$SERVERNAME" > "$HTTPD_GLOBAL"
  printf '# generated by izpbx-init (services/httpd.sh): https listens in sites-available/izpbx.conf\nListen %s\n' "$APP_PORT_HTTP" > "$HTTPD_CONF_DIR/ports.conf"
  sed -i -e "s/^export APACHE_RUN_USER=.*/export APACHE_RUN_USER=${APP_USR}/" \
         -e "s/^export APACHE_RUN_GROUP=.*/export APACHE_RUN_GROUP=${APP_GRP}/" "$HTTPD_CONF_DIR/envvars"

  {
    echo "
# global settings (server config context, inherited by all virtualhosts)
# reject request bodies bigger than PHP post_max_size (128M) before reaching PHP
LimitRequestBody 134217728
"
    echo "# default virtualhost

<VirtualHost *:${APP_PORT_HTTP}>
  DocumentRoot /var/www/html"
    [ "$HTTPD_REDIRECT_HTTP_TO_HTTPS" == "true" ] && _httpd_redirect_default
    echo "
  <Directory /var/www/html>
    Options Includes FollowSymLinks
    AllowOverride All
$(_httpd_allow_from)
  </Directory>
</VirtualHost>
"
    if [ -n "$APP_FQDN" ]; then
      echo "# ${APP_FQDN} virtualhost
  <VirtualHost *:${APP_PORT_HTTP}>
    ServerName ${APP_FQDN}"
      [ "$HTTPD_REDIRECT_HTTP_TO_HTTPS" == "true" ] && _httpd_redirect_fqdn
      echo "<Directory /var/www/html>
    Options Includes FollowSymLinks
    AllowOverride All
$(_httpd_allow_from)
  </Directory>
</VirtualHost>
"
    fi
  } > "$HTTPD_VHOST"

  [ "$HTTPD_HTTPS_ENABLED" == "true" ] || return 0
  _httpd_selfsigned
  {
    echo "
# enable HTTPS listening
Listen ${APP_PORT_HTTPS} https
SSLPassPhraseDialog    exec:/usr/share/apache2/ask-for-passphrase
SSLSessionCache        shmcb:\${APACHE_RUN_DIR}/ssl_scache(512000)
SSLSessionCacheTimeout 300
SSLCryptoDevice        builtin
"
    if [ -z "$APP_FQDN" ] && [ "$LETSENCRYPT_ENABLED" == "true" ]; then
      log_warn "httpd: LETSENCRYPT_ENABLED=true without APP_FQDN: using the self-signed certificate"
    fi
    if [ -n "$APP_FQDN" ] && [ "$LETSENCRYPT_ENABLED" == "true" ]; then
      echo "# enable ssl virtualhost using Let's Encrypt certificates
<VirtualHost *:${APP_PORT_HTTPS}>
  ServerName ${APP_FQDN}

  ErrorLog                 \${APACHE_LOG_DIR}/ssl_error_log
  TransferLog              \${APACHE_LOG_DIR}/ssl_access_log
  LogLevel                 warn
  
  SSLEngine               on
  SSLHonorCipherOrder     on
  SSLCipherSuite          ${HTTPD_CIPHERS}
  SSLProxyCipherSuite     ${HTTPD_CIPHERS}
  SSLCertificateFile      ${CERTKEYLOC}/integration/webserver.crt
  SSLCertificateKeyFile   ${CERTKEYLOC}/integration/webserver.key
  SSLCertificateChainFile ${CERTKEYLOC}/integration/certificate.pem
  
  <Directory /var/www/html>
    Options Includes FollowSymLinks
    AllowOverride All
$(_httpd_allow_from)
  </Directory>
</VirtualHost>
"
    else
      echo "# enable default ssl virtualhost with self signed certificate
<VirtualHost _default_:${APP_PORT_HTTPS}>
  ErrorLog                 \${APACHE_LOG_DIR}/ssl_error_log
  TransferLog              \${APACHE_LOG_DIR}/ssl_access_log
  LogLevel                 warn
  
  SSLEngine                on
  SSLHonorCipherOrder      on
  SSLCipherSuite           ${HTTPD_CIPHERS}
  SSLProxyCipherSuite      ${HTTPD_CIPHERS}
  SSLCertificateFile       ${HTTPD_HTTPS_CERT_FILE}
  SSLCertificateKeyFile    ${HTTPD_HTTPS_KEY_FILE}
  $([ -n "$HTTPD_HTTPS_CHAIN_FILE" ] && echo "SSLCertificateChainFile  ${HTTPD_HTTPS_CHAIN_FILE}")

  <Directory /var/www/html>
    Options Includes FollowSymLinks
    AllowOverride All
$(_httpd_allow_from)
  </Directory>
</VirtualHost>
"
    fi
  } >> "$HTTPD_VHOST"
}
